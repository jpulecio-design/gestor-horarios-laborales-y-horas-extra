-- ============================================================
-- Esquema completo del Gestor de Horarios Laborales y Horas Extra.
--
-- Crea TODAS las tablas que necesitan los modulos del backend:
--   EMPLEADO, CONTACTO_EMERGENCIA, HORA_EXTRA, NOMINA,
--   ASISTENCIA, TURNO, ASIGNACION_HORARIO, HORARIO_ASIGNADO,
--   BACKUP_HISTORIAL.
--
-- Ejecutar UNA sola vez sobre un esquema Oracle vacio (por ejemplo
-- el usuario de la aplicacion o el PDB FREEPDB1).
--
--   sqlplus usuario/clave@localhost:1521/FREEPDB1 @db/esquema.sql
--   o, sin sqlplus:   node scripts/db.js crear
--
-- Los datos de ejemplo estan en db/datos.sql.
-- ============================================================


-- ------------------------------------------------------------
-- EMPLEADO
-- Tabla base. Todo el sistema gira alrededor de ella.
-- El rol define que puede hacer cada usuario:
--   Empleado | Administrador | Contadora
-- codigo_qr es el token unico que va dentro del QR (CU03); puede ser
-- NULL en empleados antiguos (Oracle admite varios NULL en un unique).
-- ------------------------------------------------------------
CREATE TABLE EMPLEADO (
    id_empleado       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR2(60)  NOT NULL,
    apellido          VARCHAR2(60)  NOT NULL,
    cedula            VARCHAR2(20)  NOT NULL,
    correo            VARCHAR2(120) NOT NULL,
    contrasena        VARCHAR2(120) NOT NULL,
    telefono          VARCHAR2(20),
    rol               VARCHAR2(20)  DEFAULT 'Empleado' NOT NULL,
    estado            VARCHAR2(10)  DEFAULT 'Activo'   NOT NULL,
    cargo             VARCHAR2(60),
    salario_base      NUMBER,
    telegram_chat_id  VARCHAR2(30),
    codigo_qr         VARCHAR2(64),
    fecha_ingreso     DATE,
    fecha_creacion    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_empleado            PRIMARY KEY (id_empleado),
    CONSTRAINT uq_empleado_cedula     UNIQUE (cedula),
    CONSTRAINT uq_empleado_correo     UNIQUE (correo),
    CONSTRAINT uq_empleado_codigo_qr  UNIQUE (codigo_qr),
    CONSTRAINT ck_empleado_rol        CHECK (rol IN ('Empleado', 'Administrador', 'Contadora')),
    CONSTRAINT ck_empleado_estado     CHECK (estado IN ('Activo', 'Inactivo'))
);

CREATE INDEX ix_empleado_rol ON EMPLEADO (rol);


-- ------------------------------------------------------------
-- CONTACTO DE EMERGENCIA
-- Un empleado puede tener uno o varios contactos.
-- ------------------------------------------------------------
CREATE TABLE CONTACTO_EMERGENCIA (
    id_contacto   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_empleado   NUMBER NOT NULL,
    nombre        VARCHAR2(80) NOT NULL,
    telefono      VARCHAR2(20),
    parentesco    VARCHAR2(30),
    CONSTRAINT pk_contacto_emergencia PRIMARY KEY (id_contacto),
    CONSTRAINT fk_contacto_empleado FOREIGN KEY (id_empleado)
        REFERENCES EMPLEADO (id_empleado)
);

CREATE INDEX ix_contacto_empleado ON CONTACTO_EMERGENCIA (id_empleado);


-- ------------------------------------------------------------
-- HORAS EXTRA
-- ------------------------------------------------------------
CREATE TABLE HORA_EXTRA (
    id_hora_extra    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_empleado      NUMBER NOT NULL,
    fecha            DATE NOT NULL,
    tipo             VARCHAR2(20) NOT NULL,
    cantidad_horas   NUMBER NOT NULL,
    valor_hora_base  NUMBER NOT NULL,
    factor_recargo   NUMBER NOT NULL,
    valor            NUMBER NOT NULL,
    estado           VARCHAR2(10) DEFAULT 'Activo' NOT NULL,
    fecha_creacion   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_hora_extra PRIMARY KEY (id_hora_extra),
    CONSTRAINT fk_hora_extra_empleado FOREIGN KEY (id_empleado)
        REFERENCES EMPLEADO (id_empleado)
);

CREATE INDEX ix_hora_extra_empleado ON HORA_EXTRA (id_empleado);
CREATE INDEX ix_hora_extra_empleado_fecha ON HORA_EXTRA (id_empleado, fecha);


-- ------------------------------------------------------------
-- NOMINA
-- Una liquidacion por empleado y periodo (AAAA-MM).
-- ------------------------------------------------------------
CREATE TABLE NOMINA (
    id_nomina               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_empleado             NUMBER NOT NULL,
    periodo                 VARCHAR2(7) NOT NULL,
    horas_recargo_nocturno  NUMBER DEFAULT 0 NOT NULL,
    horas_recargo_festivo   NUMBER DEFAULT 0 NOT NULL,
    salario_base            NUMBER NOT NULL,
    valor_hora              NUMBER NOT NULL,
    pago_recargo_nocturno   NUMBER NOT NULL,
    pago_recargo_festivo    NUMBER NOT NULL,
    pago_horas_extra        NUMBER NOT NULL,
    total_devengado         NUMBER NOT NULL,
    salud                   NUMBER NOT NULL,
    pension                 NUMBER NOT NULL,
    total_deducciones       NUMBER NOT NULL,
    neto_pagar              NUMBER NOT NULL,
    estado                  VARCHAR2(10) DEFAULT 'Activo' NOT NULL,
    fecha_creacion          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_nomina PRIMARY KEY (id_nomina),
    CONSTRAINT fk_nomina_empleado FOREIGN KEY (id_empleado)
        REFERENCES EMPLEADO (id_empleado),
    CONSTRAINT uq_nomina_empleado_periodo UNIQUE (id_empleado, periodo)
);

CREATE INDEX ix_nomina_empleado ON NOMINA (id_empleado);


-- ------------------------------------------------------------
-- ASISTENCIA (CU03: entradas y salidas registradas por QR)
-- Cada fila es un marcaje; entrada o salida se alterna automaticamente.
-- ------------------------------------------------------------
CREATE TABLE ASISTENCIA (
    id_asistencia    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_empleado      NUMBER NOT NULL,
    tipo             VARCHAR2(10) NOT NULL,
    fecha_hora       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    origen           VARCHAR2(10) DEFAULT 'QR' NOT NULL,
    observacion      VARCHAR2(200),
    estado           VARCHAR2(10) DEFAULT 'Activo' NOT NULL,
    fecha_creacion   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_asistencia PRIMARY KEY (id_asistencia),
    CONSTRAINT fk_asistencia_empleado FOREIGN KEY (id_empleado)
        REFERENCES EMPLEADO (id_empleado),
    CONSTRAINT ck_asistencia_tipo CHECK (tipo IN ('Entrada', 'Salida'))
);

CREATE INDEX ix_asistencia_empleado ON ASISTENCIA (id_empleado, fecha_hora);


-- ------------------------------------------------------------
-- HORARIOS Y TURNOS (CU05: visualizar horarios asignados)
-- TURNO: plantilla reutilizable (horas + dias de la semana).
--   dias se guarda como lista de numeros ISO: 1=Lunes ... 7=Domingo.
-- ASIGNACION_HORARIO: aplica un turno a un empleado en un rango de fechas.
--   fecha_hasta nulo = vigente indefinidamente.
-- ------------------------------------------------------------
CREATE TABLE TURNO (
    id_turno         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre           VARCHAR2(50) NOT NULL,
    hora_entrada     VARCHAR2(5) NOT NULL,
    hora_salida      VARCHAR2(5) NOT NULL,
    dias             VARCHAR2(20) NOT NULL,
    estado           VARCHAR2(10) DEFAULT 'Activo' NOT NULL,
    fecha_creacion   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_turno PRIMARY KEY (id_turno),
    CONSTRAINT uq_turno_nombre UNIQUE (nombre)
);

CREATE TABLE ASIGNACION_HORARIO (
    id_asignacion    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_empleado      NUMBER NOT NULL,
    id_turno         NUMBER NOT NULL,
    fecha_desde      DATE NOT NULL,
    fecha_hasta      DATE,
    estado           VARCHAR2(10) DEFAULT 'Activo' NOT NULL,
    fecha_creacion   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_asignacion_horario PRIMARY KEY (id_asignacion),
    CONSTRAINT fk_asignacion_empleado FOREIGN KEY (id_empleado)
        REFERENCES EMPLEADO (id_empleado),
    CONSTRAINT fk_asignacion_turno FOREIGN KEY (id_turno)
        REFERENCES TURNO (id_turno)
);

CREATE INDEX ix_asignacion_empleado ON ASIGNACION_HORARIO (id_empleado, fecha_desde);

-- ------------------------------------------------------------
-- PROGRAMACION DIARIA DE HORARIOS (CU04: Parametrizar Horarios y Plantillas de Turnos)
-- Un turno concreto por empleado y fecha: es el calendario operativo.
-- Tiene prioridad sobre la plantilla (TURNO + ASIGNACION_HORARIO) al consultar CU05.
-- Si hora_salida_prog <= hora_entrada_prog el turno termina al dia siguiente (Nocturno).
--
-- Mismas columnas y CHECK que la tabla HORARIO_ASIGNADO ya existente en Oracle.
-- id_plantilla_origen queda nullable y sin FK porque este backend no maneja PLANTILLA_TURNO.
-- uq_horario_empleado_fecha impide duplicados; en una base donde la tabla ya exista sin
-- esa restriccion, agregarla con:
--   ALTER TABLE HORARIO_ASIGNADO ADD CONSTRAINT uq_horario_empleado_fecha UNIQUE (id_empleado, fecha);
-- ------------------------------------------------------------
CREATE TABLE HORARIO_ASIGNADO (
    id_horario           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_empleado          NUMBER NOT NULL,
    id_plantilla_origen  NUMBER,
    fecha                DATE NOT NULL,
    hora_entrada_prog    VARCHAR2(5) NOT NULL,
    hora_salida_prog     VARCHAR2(5) NOT NULL,
    tipo_turno           VARCHAR2(15) NOT NULL,
    CONSTRAINT pk_horario_asignado PRIMARY KEY (id_horario),
    CONSTRAINT fk_horario_empleado FOREIGN KEY (id_empleado)
        REFERENCES EMPLEADO (id_empleado),
    CONSTRAINT ck_horario_tipo CHECK (tipo_turno IN ('Diurno', 'Vespertino', 'Nocturno')),
    CONSTRAINT uq_horario_empleado_fecha UNIQUE (id_empleado, fecha)
);


-- ------------------------------------------------------------
-- HISTORIAL DE BACKUPS (CU11: seguridad y respaldos)
-- Un registro por cada respaldo generado (manual o automatico).
-- id_empleado = quien lo genero (NULL en los automaticos).
-- ------------------------------------------------------------
CREATE TABLE BACKUP_HISTORIAL (
    id_backup        NUMBER GENERATED ALWAYS AS IDENTITY,
    fecha_hora       DATE DEFAULT SYSDATE NOT NULL,
    nombre_archivo   VARCHAR2(150),
    tipo             VARCHAR2(15) NOT NULL,
    estado           VARCHAR2(15) NOT NULL,
    id_empleado      NUMBER,
    intentos         NUMBER DEFAULT 1 NOT NULL,
    tamano_bytes     NUMBER,
    detalle_error    VARCHAR2(255),
    CONSTRAINT pk_backup_historial PRIMARY KEY (id_backup),
    CONSTRAINT ck_backup_tipo   CHECK (tipo IN ('Manual', 'Automatico')),
    CONSTRAINT ck_backup_estado CHECK (estado IN ('Exitoso', 'Fallido')),
    CONSTRAINT fk_backup_empleado FOREIGN KEY (id_empleado)
        REFERENCES EMPLEADO (id_empleado)
);

-- ------------------------------------------------------------
-- PROGRAMACION DIARIA DE HORARIOS (CU04: Parametrizar Horarios y Plantillas de Turnos)
-- Un turno concreto por empleado y fecha: es el calendario operativo.
